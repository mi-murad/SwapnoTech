export function insightReadingTime(article, lang = 'EN') {
  const words = [
    article.summary?.[lang === 'BN' ? 'bn' : 'en'] || '',
    ...(article.sections || []).flatMap(section => [
      section.heading?.[lang === 'BN' ? 'bn' : 'en'] || '',
      ...(section.paragraphs || []).map(item => item[lang === 'BN' ? 'bn' : 'en'] || ''),
      ...(section.bullets || []).map(item => item[lang === 'BN' ? 'bn' : 'en'] || '')
    ])
  ].join(' ').trim().split(/\s+/).filter(Boolean).length;
  const minutes = Math.max(2, Math.ceil(words / (lang === 'BN' ? 110 : 190)));
  return lang === 'BN' ? `প্রায় ${minutes} মিনিট` : `${minutes} min read`;
}
